    [Fact]
    public async Task TestPartialMethodPartsInDifferentDocumentsAreUpdatedTogetherAsync()
    {
        var definition = @"
internal partial class TypeName
{
    {|#0:public|} partial void MethodName();
}
";
        var implementation = @"
internal partial class TypeName
{
    {|#1:public|} partial void MethodName()
    {
    }
}
";
        var fixedDefinition = @"
internal partial class TypeName
{
    internal partial void MethodName();
}
";
        var fixedImplementation = @"
internal partial class TypeName
{
    internal partial void MethodName()
    {
    }
}
";

        var test = new CSharpTest();
        test.TestState.Sources.Add(definition);
        test.TestState.Sources.Add(implementation);
        test.FixedState.Sources.Add(fixedDefinition);
        test.FixedState.Sources.Add(fixedImplementation);
        test.ExplicitlyEnabledDiagnostics.Add(SA1415DoNotUsePublicOnMembersOfInternalTypes.DiagnosticId);
        test.ExpectedDiagnostics.Add(Diagnostic().WithLocation(0));
        test.ExpectedDiagnostics.Add(Diagnostic().WithLocation(1));
        await test.RunAsync(CancellationToken.None).ConfigureAwait(false);
    }

