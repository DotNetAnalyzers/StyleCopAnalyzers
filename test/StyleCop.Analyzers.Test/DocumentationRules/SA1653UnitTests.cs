    [Fact]
    [WorkItem(4368, "https://github.com/DotNetAnalyzers/StyleCopAnalyzers/issues/4368")]
    public async Task TestCodeFixConvertsUniqueAndRemovesDuplicateSummariesAsync()
    {
        var source = @"/// <summary>Duplicate.</summary>
public partial class TestType { }
/// <summary>Duplicate.</summary>
public partial class TestType { }
/// <summary>Unique.</summary>
public partial class TestType { }";

        var fixedSource = @"/// <summary>Duplicate.</summary>
public partial class TestType { }
public partial class TestType { }
/// <content>Unique.</content>
public partial class TestType { }";

        await VerifyCSharpFixAsync(
            source,
            new[]
            {
                Diagnostic().WithLocation(2, 22).WithArguments("TestType"),
                Diagnostic().WithLocation(4, 22).WithArguments("TestType"),
                Diagnostic().WithLocation(6, 22).WithArguments("TestType"),
            },
            fixedSource,
            CancellationToken.None).ConfigureAwait(false);
    }

    [Fact]
    [WorkItem(4368, "https://github.com/DotNetAnalyzers/StyleCopAnalyzers/issues/4368")]
    public async Task TestCodeFixRetainsTheSummaryFromTheInvokedDeclarationAcrossDocumentsAsync()
    {
        var test = new CSharpTest
        {
            TestState =
            {
                Sources =
                {
                    ("Earlier.cs", @"#pragma warning disable SA1653
/// <summary>Earlier unique summary.</summary>
public partial class TestType { }
#pragma warning restore SA1653"),
                    ("Chosen.cs", @"/// <summary>Chosen summary.</summary>
public partial class TestType { }
/// <summary>Chosen summary.</summary>
public partial class TestType { }"),
                },
            },
            FixedState =
            {
                Sources =
                {
                    ("Earlier.cs", @"#pragma warning disable SA1653
/// <content>Earlier unique summary.</content>
public partial class TestType { }
#pragma warning restore SA1653"),
                    ("Chosen.cs", @"/// <summary>Chosen summary.</summary>
public partial class TestType { }
public partial class TestType { }"),
                },
            },
        };
        test.ExpectedDiagnostics.Add(Diagnostic().WithLocation("Chosen.cs", 2, 22).WithArguments("TestType"));
        test.ExpectedDiagnostics.Add(Diagnostic().WithLocation("Chosen.cs", 4, 22).WithArguments("TestType"));
        await test.RunAsync(CancellationToken.None).ConfigureAwait(false);
    }

