    [Fact]
    public async Task TestCodeFixPreservesNestedPartialSummaryChangesAsync()
    {
        var source = @"/// <summary>Outer A.</summary>
public partial class Outer
{
    /// <summary>Nested A.</summary>
    public partial class Nested { }
}
/// <summary>Outer B.</summary>
public partial class Outer
{
    /// <summary>Nested B.</summary>
    public partial class Nested { }
}";

        var fixedSource = @"/// <summary>Outer A.</summary>
public partial class Outer
{
    /// <summary>Nested A.</summary>
    public partial class Nested { }
}
/// <content>Outer B.</content>
public partial class Outer
{
    /// <content>Nested B.</content>
    public partial class Nested { }
}";

        await VerifyCSharpFixAsync(
            source,
            new[]
            {
                Diagnostic().WithLocation(2, 22).WithArguments("Outer"),
                Diagnostic().WithLocation(5, 26).WithArguments("Nested"),
                Diagnostic().WithLocation(8, 22).WithArguments("Outer"),
                Diagnostic().WithLocation(11, 26).WithArguments("Nested"),
            },
            fixedSource,
