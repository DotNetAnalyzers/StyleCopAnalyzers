namespace StyleCop.Analyzers.Test.CSharp13.MaintainabilityRules;

using System.Threading;
using System.Threading.Tasks;
using Microsoft.CodeAnalysis.Testing;
using StyleCop.Analyzers.MaintainabilityRules;
using StyleCop.Analyzers.Test.CSharp12.MaintainabilityRules;
using Xunit;
using static StyleCop.Analyzers.Test.Verifiers.StyleCopCodeFixVerifier<
    StyleCop.Analyzers.MaintainabilityRules.SA1415DoNotUsePublicOnMembersOfInternalTypes,
    StyleCop.Analyzers.MaintainabilityRules.SA1415CodeFixProvider>;

public partial class SA1415CSharp13UnitTests : SA1415CSharp12UnitTests
{
    [Fact]
    public async Task TestPartialPropertyPartsInOneFileAreUpdatedTogetherAsync()
    {
        var testCode = @"
internal partial class TypeName
{
    {|#0:public|} partial int PropertyName { get; set; }

    {|#1:public|} partial int PropertyName
    {
        get => 0;
        set { }
    }
}
";
        var fixedCode = @"
internal partial class TypeName
{
    internal partial int PropertyName { get; set; }

    internal partial int PropertyName
    {
        get => 0;
        set { }
    }
}
";

        await VerifyFixAsync(testCode, fixedCode, Diagnostic().WithLocation(0), Diagnostic().WithLocation(1)).ConfigureAwait(false);
    }

    [Fact]
    public async Task TestPartialPropertyPartsInDifferentDocumentsAreUpdatedTogetherAsync()
    {
        var definition = @"
internal partial class TypeName
{
    {|#0:public|} partial int PropertyName { get; set; }
}
";
        var implementation = @"
internal partial class TypeName
{
    {|#1:public|} partial int PropertyName
    {
        get => 0;
        set { }
    }
}
";
        var fixedDefinition = @"
internal partial class TypeName
{
    internal partial int PropertyName { get; set; }
}
";
        var fixedImplementation = @"
internal partial class TypeName
{
    internal partial int PropertyName
    {
        get => 0;
        set { }
    }
}
";

        var test = new CSharpTest();
        test.TestState.Sources.Add(definition);
        test.TestState.Sources.Add(implementation);
        test.FixedState.Sources.Add(fixedDefinition);
        test.FixedState.Sources.Add(fixedImplementation);
        test.ExplicitlyEnabledDiagnostics.Add(SA1415DoNotUsePublicOnMembersOfInternalTypes.DiagnosticId);
        test.ExpectedDiagnostics.Add(Diagnostic().WithLocation(0));
        test.ExpectedDiagnostics.Add(Diagnostic().WithLocation(1));
        await test.RunAsync(CancellationToken.None).ConfigureAwait(false);
    }

    [Fact]
    public async Task TestPartialPropertyWithGeneratedPartIsReportedWithoutCodeFixAsync()
    {
        var testCode = @"
internal partial class TypeName
{
    {|#0:public|} partial int PropertyName { get; set; }
}
";
        var generatedCode = @"
// <auto-generated/>
internal partial class TypeName
{
    public partial int PropertyName
    {
        get => 0;
        set { }
    }
}
";

        var test = new CSharpTest();
        test.TestState.Sources.Add(("TypeName.cs", testCode));
        test.TestState.Sources.Add(("TypeName.generated.cs", generatedCode));
        test.FixedState.Sources.Add(("TypeName.cs", testCode));
        test.FixedState.Sources.Add(("TypeName.generated.cs", generatedCode));
        test.ExplicitlyEnabledDiagnostics.Add(SA1415DoNotUsePublicOnMembersOfInternalTypes.DiagnosticId);
        var expected = Diagnostic().WithLocation(0);
        test.ExpectedDiagnostics.Add(expected);
        test.RemainingDiagnostics.Add(expected);
        await test.RunAsync(CancellationToken.None).ConfigureAwait(false);
    }

    [Fact]
    public async Task TestPartialIndexerPartsInOneFileAreUpdatedTogetherAsync()
    {
        var testCode = @"
internal partial class TypeName
{
    {|#0:public|} partial int this[int index] { get; set; }

    {|#1:public|} partial int this[int index]
    {
        get => 0;
        set { }
    }
}
";
        var fixedCode = @"
internal partial class TypeName
{
    internal partial int this[int index] { get; set; }

    internal partial int this[int index]
    {
        get => 0;
        set { }
    }
}
";

        await VerifyFixAsync(testCode, fixedCode, Diagnostic().WithLocation(0), Diagnostic().WithLocation(1)).ConfigureAwait(false);
    }

    private static Task VerifyFixAsync(string testCode, string fixedCode, params DiagnosticResult[] expected)
    {
        var test = new CSharpTest
        {
            TestCode = testCode,
            FixedCode = fixedCode,
        };
        test.ExplicitlyEnabledDiagnostics.Add(SA1415DoNotUsePublicOnMembersOfInternalTypes.DiagnosticId);
        test.ExpectedDiagnostics.AddRange(expected);
        return test.RunAsync(CancellationToken.None);
    }
}
