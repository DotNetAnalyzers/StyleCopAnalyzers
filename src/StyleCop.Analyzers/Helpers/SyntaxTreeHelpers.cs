namespace StyleCop.Analyzers.Helpers
{
    using System;
    using System.IO;
    using System.Threading;
    using Microsoft.CodeAnalysis;
    using Microsoft.CodeAnalysis.CSharp;
    using Microsoft.CodeAnalysis.Diagnostics;
    using StyleCop.Analyzers.Lightup;

    internal static class SyntaxTreeHelpers
    {
        /// <summary>
        /// A cache of the result of computing whether a document has using alias directives.
        /// </summary>
        /// <remarks>
        /// <para>This allows many analyzers that run on every token in the file to avoid checking
        /// the same state in the document repeatedly.</para>
        /// </remarks>
        private static Tuple<WeakReference<Compilation?>, UsingAliasCache?> usingAliasCache
            = Tuple.Create(new WeakReference<Compilation?>(null), default(UsingAliasCache));

        public static UsingAliasCache GetOrCreateUsingAliasCache(this Compilation compilation)
        {
            var cache = usingAliasCache;

            Compilation? cachedCompilation;
            if (!cache.Item1.TryGetTarget(out cachedCompilation) || cachedCompilation != compilation)
            {
                var replacementCache = Tuple.Create(new WeakReference<Compilation?>(compilation), (UsingAliasCache?)new UsingAliasCache());
                while (true)
                {
                    var prior = Interlocked.CompareExchange(ref usingAliasCache, replacementCache, cache);
                    if (prior == cache)
                    {
                        cache = replacementCache;
                        break;
                    }

                    cache = prior;
                    if (cache.Item1.TryGetTarget(out cachedCompilation) && cachedCompilation == compilation)
                    {
                        break;
                    }
                }
            }

            // A live matching compilation is only stored together with its initialized cache.
            return cache.Item2!;
        }

        /// <summary>
        /// Checks if a given <see cref="SyntaxTree"/> only contains whitespace. We don't want to analyze empty files.
        /// </summary>
        /// <param name="tree">The syntax tree to examine.</param>
        /// <param name="cancellationToken">The <see cref="CancellationToken"/> that the task will observe.</param>
        /// <returns>
        /// <see langword="true"/> if <paramref name="tree"/> only contains whitespace; otherwise,
        /// <see langword="false"/>.
        /// </returns>
        public static bool IsWhitespaceOnly(this SyntaxTree tree, CancellationToken cancellationToken)
        {
            var root = tree.GetRoot(cancellationToken);
            var firstToken = root.GetFirstToken(includeZeroWidth: true);

            return firstToken.IsKind(SyntaxKind.EndOfFileToken)
                && TriviaHelper.IndexOfFirstNonWhitespaceTrivia(firstToken.LeadingTrivia) == -1;
        }

        public static bool IsEmpty(this SyntaxTree tree)
        {
            return tree.Length == 0;
        }

        /// <summary>
        /// Determines whether <paramref name="tree"/> appears to be generated code, matching Roslyn's usual
        /// generated-code heuristics: an explicit <c>generated_code</c> analyzer-config setting, common
        /// generated file-name patterns, or an <c>&lt;auto-generated</c> / <c>&lt;autogenerated</c> marker in
        /// ordinary leading comment trivia.
        /// </summary>
        /// <param name="tree">The syntax tree to examine.</param>
        /// <param name="options">The analyzer options for the compilation, used to read <c>generated_code</c>.</param>
        /// <param name="cancellationToken">The <see cref="CancellationToken"/> that the task will observe.</param>
        /// <returns>
        /// <see langword="true"/> if <paramref name="tree"/> appears to be generated; otherwise,
        /// <see langword="false"/>.
        /// </returns>
        public static bool IsGeneratedDocument(this SyntaxTree tree, AnalyzerOptions options, CancellationToken cancellationToken)
        {
            AnalyzerConfigOptionsWrapper analyzerConfigOptions = options.AnalyzerConfigOptionsProvider().GetOptions(tree);
            if (analyzerConfigOptions.TryGetValue("generated_code", out string? generatedCodeValue)
                && bool.TryParse(generatedCodeValue, out bool isGenerated))
            {
                return isGenerated;
            }

            if (IsGeneratedCodeFile(tree.FilePath))
            {
                return true;
            }

            SyntaxNode root = tree.GetRoot(cancellationToken);
            foreach (SyntaxTrivia trivia in root.GetLeadingTrivia())
            {
                if (!trivia.IsKind(SyntaxKind.SingleLineCommentTrivia)
                    && !trivia.IsKind(SyntaxKind.MultiLineCommentTrivia))
                {
                    continue;
                }

                string text = trivia.ToString();
                if (text.IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0
                    || text.IndexOf("<autogenerated", StringComparison.OrdinalIgnoreCase) >= 0)
                {
                    return true;
                }
            }

            return false;
        }

        private static bool IsGeneratedCodeFile(string? filePath)
        {
            if (string.IsNullOrEmpty(filePath))
            {
                return false;
            }

            string fileName = Path.GetFileName(filePath);
            if (fileName.StartsWith("TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }

            string fileNameWithoutExtension = Path.GetFileNameWithoutExtension(filePath);
            return fileNameWithoutExtension.EndsWith(".designer", StringComparison.OrdinalIgnoreCase)
                || fileNameWithoutExtension.EndsWith(".generated", StringComparison.OrdinalIgnoreCase)
                || fileNameWithoutExtension.EndsWith(".g", StringComparison.OrdinalIgnoreCase)
                || fileNameWithoutExtension.EndsWith(".g.i", StringComparison.OrdinalIgnoreCase);
        }
    }
}
